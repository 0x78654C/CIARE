using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CIARE.Designer;

[System.Runtime.Versioning.SupportedOSPlatform("windows")]
internal static class DesignCodeGenerator
{
    internal const string Marker = "// <auto-generated by CIARE Form Designer>";
    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text ?? "", true);
    internal static string GenerateDesigner(DesignDocument document)
    {
        document.Validate();
        var root = document.Form;
        var nodes = document.AllNodes.ToArray();
        var code = new StringBuilder();
        code.AppendLine(Marker).AppendLine("// Edit the .ciareform layout in CIARE; this file is regenerated.")
            .AppendLine($"namespace {root.Namespace}").AppendLine("{")
            .AppendLine($"    public partial class {root.Name}").AppendLine("    {");
        foreach (var node in nodes.Skip(1)) code.AppendLine($"        private global::System.Windows.Forms.{node.Kind} {node.Name};");
        code.AppendLine().AppendLine("        private void InitializeComponent()").AppendLine("        {");
        foreach (var node in nodes.Skip(1)) code.AppendLine($"            this.{node.Name} = new global::System.Windows.Forms.{node.Kind}();");
        foreach (var node in nodes.Where(n => n.IsContainer)) code.AppendLine($"            {Target(node)}.SuspendLayout();");
        code.AppendLine("            this.AutoScaleMode = global::System.Windows.Forms.AutoScaleMode.None;");
        foreach (var node in nodes)
        {
            string target = Target(node);
            void Set(string property, string value) => code.AppendLine($"            {target}.{property} = {value};");
            code.AppendLine($"            // {node.Name}");
            Set("Name", Literal(node.Name));
            if (node.Kind is not ("DateTimePicker" or "NumericUpDown")) Set("Text", Literal(node.Text));
            if (node.Kind == "DateTimePicker") Set("Value", $"new global::System.DateTime({node.Date.Ticks}L)");
            Set(node == root ? "ClientSize" : "Size", $"new global::System.Drawing.Size({node.Width}, {node.Height})");
            Set("BackColor", $"global::System.Drawing.Color.FromArgb({node.BackColorArgb})");
            Set("ForeColor", $"global::System.Drawing.Color.FromArgb({node.ForeColorArgb})");
            Set("Font", $"new global::System.Drawing.Font(\"Segoe UI\", {node.FontSize.ToString(System.Globalization.CultureInfo.InvariantCulture)}F)");
            if (node != root)
            {
                Set("AutoSize", "false");
                Set("Location", $"new global::System.Drawing.Point({node.X}, {node.Y})");
                Set("Anchor", $"(global::System.Windows.Forms.AnchorStyles){(int)node.Anchor}");
                Set("Dock", $"global::System.Windows.Forms.DockStyle.{node.Dock}");
                Set("TabIndex", node.TabIndex.ToString());
            }
            if (!node.Enabled) Set("Enabled", "false");
            if (!node.Visible && node != root) Set("Visible", "false");
            if (node.Kind is "CheckBox" or "RadioButton") Set("Checked", node.Checked ? "true" : "false");
            if (node.Kind == "TextBox") Set("Multiline", node.Multiline ? "true" : "false");
            if (node.Kind == "ListBox") Set("IntegralHeight", "false");
            if (node.Kind == "PictureBox") Set("BorderStyle", "global::System.Windows.Forms.BorderStyle.FixedSingle");
            if (node.Kind is "NumericUpDown" or "ProgressBar" or "TrackBar")
            {
                Set("Maximum", node.Maximum.ToString()); Set("Minimum", node.Minimum.ToString()); Set("Value", node.Value.ToString());
            }
            if (node.Kind is "ComboBox" or "ListBox" && node.Items.Length > 0)
                code.AppendLine($"            {target}.Items.AddRange(new object[] {{ {string.Join(", ", node.Items.Select(Literal))} }});");
            foreach (var binding in node.Events.OrderBy(e => e.Key)) code.AppendLine($"            {target}.{binding.Key} += this.{binding.Value};");
        }
        // Preserve collection order: index zero is the frontmost control in WinForms.
        foreach (var parent in nodes.Where(n => n.IsContainer))
            foreach (var child in parent.Children) code.AppendLine($"            {Target(parent)}.Controls.Add(this.{child.Name});");
        foreach (var node in nodes.Reverse().Where(n => n.IsContainer))
        {
            code.AppendLine($"            {Target(node)}.ResumeLayout(false);");
            code.AppendLine($"            {Target(node)}.PerformLayout();");
        }
        return code.AppendLine("        }").AppendLine("    }").AppendLine("}").ToString();
        string Target(DesignNode node) => node == root ? "this" : "this." + node.Name;
    }

    internal static string GenerateCodeBehind(DesignDocument document, string existing = null)
    {
        document.Validate();
        var root = document.Form;
        if (existing == null)
        {
            existing = $"// Event-handler code is preserved when the layout is exported again.\r\nnamespace {root.Namespace}\r\n{{\r\n" +
                $"    public partial class {root.Name} : global::System.Windows.Forms.Form\r\n    {{\r\n" +
                $"        public {root.Name}()\r\n        {{\r\n            InitializeComponent();\r\n        }}\r\n    }}\r\n}}\r\n";
        }
        var tree = CSharpSyntaxTree.ParseText(existing);
        if (tree.GetDiagnostics().Any(d => d.Severity == DiagnosticSeverity.Error))
            throw new InvalidDataException("Fix syntax errors in the existing code-behind before exporting.");
        var classes = tree.GetRoot().DescendantNodes().OfType<ClassDeclarationSyntax>().Where(c => c.Identifier.ValueText == root.Name &&
            string.Join(".", c.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().Reverse().Select(n => n.Name.ToString())) == root.Namespace).ToArray();
        if (classes.Length != 1 || !classes[0].Modifiers.Any(SyntaxKind.PartialKeyword))
            throw new InvalidDataException("The existing code file must contain the matching partial form class. Choose a different export name or location.");
        var declaration = classes[0];
        var methods = declaration.Members.OfType<MethodDeclarationSyntax>().ToArray();
        var handlers = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var node in document.AllNodes)
            foreach (var binding in node.Events) handlers[binding.Value] = DesignCatalog.EventsFor(node.Kind).First(e => e.Name == binding.Key).ArgumentType;
        var additions = new StringBuilder();
        foreach (var handler in handlers.OrderBy(h => h.Key))
        {
            var existingMethods = methods.Where(m => m.Identifier.ValueText == handler.Key).ToArray();
            if (existingMethods.Length > 0)
            {
                if (!existingMethods.Any(m => m.ReturnType is PredefinedTypeSyntax p && p.Keyword.IsKind(SyntaxKind.VoidKeyword) &&
                    !m.Modifiers.Any(SyntaxKind.StaticKeyword) && m.TypeParameterList == null && m.ParameterList.Parameters.Count == 2 &&
                    m.ParameterList.Parameters.All(p => p.Modifiers.Count == 0) &&
                    IsType(m.ParameterList.Parameters[0].Type, "System.Object") && IsType(m.ParameterList.Parameters[1].Type, handler.Value)))
                    throw new InvalidDataException($"Handler {handler.Key} must have signature void {handler.Key}(object sender, {handler.Value} e).");
                continue;
            }
            if (declaration.Members.OfType<PropertyDeclarationSyntax>().Any(p => p.Identifier.ValueText == handler.Key) ||
                declaration.Members.OfType<FieldDeclarationSyntax>().Any(f => f.Declaration.Variables.Any(v => v.Identifier.ValueText == handler.Key)))
                throw new InvalidDataException("The event handler name conflicts with a code-behind member: " + handler.Key);
            additions.AppendLine().AppendLine($"        private void {handler.Key}(object sender, global::{handler.Value} e)")
                .AppendLine("        {").AppendLine("            // Add your event-handler code here.").AppendLine("        }");
        }
        if (additions.Length == 0) return existing;
        // Insert only new members; retain all existing text, comments and handler bodies byte for byte.
        int position = declaration.CloseBraceToken.SpanStart;
        int lineStart = existing.LastIndexOf('\n', Math.Max(0, position - 1)) + 1;
        if (existing.Substring(lineStart, position - lineStart).All(char.IsWhiteSpace)) position = lineStart;
        return existing.Insert(position, additions.ToString());
    }
    private static bool IsType(TypeSyntax syntax, string fullName)
    {
        string name = syntax?.ToString().Replace("global::", "").TrimEnd('?');
        return name == fullName || name == fullName.Split('.').Last() || fullName == "System.Object" && name == "object";
    }

    internal static (string CodePath, string DesignerPath) Export(DesignDocument document, string codePath)
    {
        string designerPath = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(codePath)), Path.GetFileNameWithoutExtension(codePath) + ".Designer.cs");
        string previousCode = File.Exists(codePath) ? File.ReadAllText(codePath) : null;
        string previousDesigner = File.Exists(designerPath) ? File.ReadAllText(designerPath) : null;
        if (previousDesigner != null && !previousDesigner.StartsWith(Marker, StringComparison.Ordinal))
            throw new InvalidDataException("The target .Designer.cs was not generated by CIARE. Choose another location to protect the existing form.");
        string designer = GenerateDesigner(document);
        string code = GenerateCodeBehind(document, previousCode);
        DesignDocument.WriteAtomic(codePath, code);
        try { DesignDocument.WriteAtomic(designerPath, designer); }
        catch
        {
            if (previousCode == null) File.Delete(codePath); else DesignDocument.WriteAtomic(codePath, previousCode);
            throw;
        }
        return (codePath, designerPath);
    }
}
